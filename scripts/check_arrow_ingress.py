"""Closed inventory: every Python callable, explicit Rust Arrow signatures.

Unsupported Rust indirection is rejected independently of ingress selection.
Runtime inspection of the installed wheel complements source extraction in CI.
Registry entries are reviewed evidence, never regenerated by this gate.
"""
from pathlib import Path
import ast
import copy
import hashlib
import inspect
import importlib
import pkgutil
import json
import re
import sys
from functools import lru_cache
try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10 in the SDK matrix
    import tomli as tomllib

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "scripts/arrow_ingress_registry.json"


@lru_cache(maxsize=1)
def arrow_types():
    from arrow_public_items import load_catalog
    names = set(load_catalog()['types'])
    upstream_names = frozenset(names)
    # Project stream traits are Arrow-bearing through their declared methods.
    for path in (ROOT / 'crates').glob('*/src/**/*.rs'):
        source = rust_mask(path.read_text(encoding='utf-8'))
        for match in re.finditer(r'\bpub\s+trait\s+(\w+)[^{]*\{', source):
            depth, end = 1, match.end()
            while depth and end < len(source):
                depth += (source[end] == '{') - (source[end] == '}')
                end += 1
            if any(upstream_names.intersection(re.findall(r'\b\w+\b', result))
                   for result in re.findall(r'->([^;{]+)', source[match.end():end])):
                names.add(match[1])
    return names


def digest(text):
    return hashlib.sha256(text.encode()).hexdigest()


def rust_mask(source):
    """Mask comments and string/character literals, preserving offsets."""
    pattern = r'//[^\n]*|/\*[\s\S]*?\*/|r(\#*)"[\s\S]*?"\1|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])\''
    return re.sub(pattern, lambda m: " " * len(m[0]), source, flags=re.DOTALL)


def arrow_words(masked):
    """Direct imports only; aliases are handled by the independent refusal."""
    words = set()
    for match in re.finditer(r'\buse\s+[^;]+;', masked):
        if re.search(r'\b(?:arrow\w*|parquet)\b', match[0]):
            words.update(re.findall(r'\b[A-Z]\w*\b', match[0]))
    return words


def mentions_arrow(text, words):
    return bool(arrow_types().intersection(re.findall(r'\b\w+\b', text)) or re.search(r'\b(?:arrow\w*|parquet)\s*::', text)
                or words.intersection(re.findall(r'\b\w+\b', text)))


def rust_header_end(masked, end):
    """Find the item delimiter outside parameter lists and generic arguments."""
    parens = brackets = angles = 0
    while end < len(masked):
        char = masked[end]
        if char in '{;' and not parens and not brackets and not angles:
            break
        parens += (char == '(') - (char == ')')
        brackets += (char == '[') - (char == ']')
        if char == '<':
            angles += 1
        elif char == '>' and masked[end - 1] != '-':
            angles = max(0, angles - 1)
        end += 1
    return end


def rust_functions(path, source):
    masked = rust_mask(source)
    imported_arrow = arrow_words(masked)
    counts = {}
    # Include restricted visibility and native methods too: a conservative
    # superset avoids silently losing PyO3's implicitly exported methods.
    native = "plenora-database-py/src/" in path
    pattern = r"\b(?P<pub>pub(?:\([^)]*\))?\s+)?(?:async\s+|const\s+|unsafe\s+|extern\s+)*fn\s+(?P<name>\w+)"
    # Trait implementations are included conservatively even when the trait
    # is imported from another module/crate. No visibility inference is needed.
    containers = []
    for owner in re.finditer(r'\b(?:pub(?:\([^)]*\))?\s+(?:(?:unsafe|auto)\s+)?trait\s+\w+|impl\b)', masked):
        opening = rust_header_end(masked, owner.end())
        if opening == len(masked) or masked[opening] != '{':
            continue
        header = masked[owner.start():opening]
        if not header.startswith('pub') and not re.search(r'\bfor\b', header):
            continue
        depth, close = 1, opening + 1
        while depth and close < len(masked):
            depth += (masked[close] == '{') - (masked[close] == '}')
            close += 1
        containers.append((opening + 1, close))
    for match in re.finditer(pattern, masked):
        implicit = any(start <= match.start() < end for start, end in containers)
        if not match['pub'] and not native and not implicit:
            continue
        start = match.start()
        end = rust_header_end(masked, match.end())
        if end == len(masked):
            raise ValueError(f"unparsed Rust signature: {path}")
        signature = source[start:end]
        if not native and not mentions_arrow(signature, imported_arrow):
            continue
        close = end
        if masked[end] == "{":
            depth = 1
            close += 1
            while depth and close < len(masked):
                depth += (masked[close] == "{") - (masked[close] == "}")
                close += 1
            if depth:
                raise ValueError(f"unclosed Rust body: {path}")
        name = match['name']
        counts[name] = counts.get(name, 0) + 1
        key = f"{path}::{name}#{counts[name]}"
        docs = []
        for line in reversed(source[:start].rstrip().splitlines()):
            if not line.strip().startswith(('///', '#[')):
                break
            docs.append(line.strip())
        yield key, {"signature": " ".join(signature.split()), "docs": '\n'.join(reversed(docs)),
                    "body": source[end:close], "review_sha256": digest(source[start:close])}


def python_functions(path, source):
    tree = ast.parse(source)

    def walk(nodes, owners=()):
        for node in nodes:
            if isinstance(node, ast.ClassDef):
                decorators = [ast.unparse(d) for d in node.decorator_list]
                if any('dataclass' in d for d in decorators) and not any(
                    isinstance(n, ast.FunctionDef) and n.name == '__init__' for n in node.body
                ):
                    fields = [n for n in node.body if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name)]
                    parameters = [inspect.Parameter(n.target.id, inspect.Parameter.KEYWORD_ONLY,
                                                    annotation=ast.unparse(n.annotation)) for n in fields]
                    signature = inspect.Signature(parameters)
                    key = f"{path}::{'.'.join((*owners, node.name, '__init__'))}"
                    yield key, {'signature': f'dataclass {signature}', 'body': ast.unparse(node),
                                'review_sha256': digest(ast.dump(node, include_attributes=False))}
                yield from walk(node.body, (*owners, node.name))
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if node.name.startswith('_') and not (node.name.startswith('__') and node.name.endswith('__')):
                    continue
                args = copy.deepcopy(node.args)
                for arg in [*args.posonlyargs, *args.args, *args.kwonlyargs, args.vararg, args.kwarg]:
                    if arg is not None and arg.annotation is not None:
                        arg.annotation = ast.Constant(ast.unparse(arg.annotation))
                args.defaults = [ast.Constant(None) for _ in args.defaults]
                args.kw_defaults = [ast.Constant(None) if x is not None else None for x in args.kw_defaults]
                stub = ast.FunctionDef(name=node.name, args=args, body=[ast.Pass()], decorator_list=[],
                                       returns=ast.Constant(ast.unparse(node.returns)) if node.returns else None)
                module = ast.fix_missing_locations(ast.Module(body=[stub], type_ignores=[]))
                namespace = {}
                exec(compile(module, path, 'exec'), namespace)
                signature = inspect.signature(namespace[node.name])
                key = f"{path}::{'.'.join((*owners, node.name))}"
                # Overloads are declarations; the concrete implementation wins.
                yield key, {"signature": str(signature), "body": ast.unparse(node),
                            "review_sha256": digest(ast.dump(node, include_attributes=False))}
            else:
                for field in ('body', 'orelse', 'finalbody'):
                    yield from walk(getattr(node, field, []), owners)
                for handler in getattr(node, 'handlers', []):
                    yield from walk(handler.body, owners)
    yield from walk(tree.body)


def inventory(sources):
    result = {}
    for path, source in sorted(sources.items()):
        if path.startswith('crates/') and path.endswith('.rs') and '/src/' not in path:
            continue
        parser = python_functions if path.endswith(('.py', '.pyi')) else rust_functions
        result.update(parser(path, source))
    return result


def sources():
    members = tomllib.loads((ROOT / 'Cargo.toml').read_text(encoding='utf-8'))['workspace']['members']
    result = {}
    for member in members:
        for path in (ROOT / member).rglob('*.rs'):
            result[path.relative_to(ROOT).as_posix()] = path.read_text(encoding='utf-8')
    for path in (ROOT / 'crates/plenora-database-py/python/plenora_database').rglob('*.py'):
        result[path.relative_to(ROOT).as_posix()] = path.read_text(encoding='utf-8')
    return result


def audit(found, registry, support=None, source_map=None):
    errors = []
    for key in sorted(found.keys() - registry.keys()):
        errors.append(f'unclassified: {key}')
    for key in sorted(registry.keys() - found.keys()):
        errors.append(f'stale classification: {key}')
    for key in sorted(found.keys() & registry.keys()):
        item, rule = found[key], registry[key]
        if rule.get('classification') not in {'ingresso guardato', 'helper con precondizione dichiarata', 'non riceve dati Arrow esterni'}:
            errors.append(f'invalid classification: {key}')
        if not rule.get('reason') or rule.get('review_sha256') != item['review_sha256']:
            errors.append(f'unreviewed implementation: {key}')
        if rule.get('signature') != item['signature']:
            errors.append(f'stale signature: {key}')
        if rule.get('classification') == 'ingresso guardato':
            if not rule.get('proof') or not rule.get('required'):
                errors.append(f'missing proof: {key}')
            for token in rule.get('required', []):
                if token not in item['body']:
                    errors.append(f'missing guard {token}: {key}')
        if rule.get('classification') == 'helper con precondizione dichiarata':
            if not rule.get('limit') or not rule.get('precondition'):
                errors.append(f'missing limit/precondition: {key}')
            for token in rule.get('precondition', []):
                if token not in item.get('docs', ''):
                    errors.append(f'missing documented precondition: {key}')
    for path, rule in (support or {}).items():
        source = (source_map or {}).get(path)
        if source is None or digest(source) != rule.get('review_sha256'):
            errors.append(f'unreviewed guard chain: {path}')
    return errors


def rust_forms(path, source):
    """Reject indirection before selecting explicit signatures.

    Bounds are deliberately conservative (also on private items): accepting a
    broader grammar requires a reviewed exception, not another inference rule.
    """
    if not path.endswith('.rs') or 'vendor' in Path(path).parts or any(
        part == 'tests' or part.endswith('_tests.rs') or part == 'tests.rs'
        for part in Path(path).parts
    ):
        return
    masked = rust_mask(source)
    imported_arrow = arrow_words(masked)
    patterns = {
        'alias': r'\buse\s+[^;]+\bas\s+\w+[^;]*;|\btype\s+\w+[^;=]*=[^;]+;',
        'bound': r'\b(?:impl|fn|trait|struct|enum)\b',
        'reexport': r'\bpub(?:\([^)]*\))?\s+use\s+[^;]+;',
    }
    for kind, pattern in patterns.items():
        counts = {}
        consumed = -1
        for match in re.finditer(pattern, masked):
            if match.start() < consumed:
                continue
            end = rust_header_end(masked, match.end()) if kind == 'bound' else match.end()
            consumed = end
            text = masked[match.start():end]
            arrow = mentions_arrow(text, imported_arrow) or re.search(r'\b(?:arrow\w*|parquet)\b', text)
            if kind == 'alias' and not arrow:
                continue
            # Inspect every bound position, including where clauses, nested
            # associated constraints and bounds following ordinary traits.
            bound_pattern = r'(?:\bimpl\s+|(?<!:):(?!:)\s*|\+\s*)(?:for\s*<[^>]*>\s*)?[?~]?([\w:]+)'
            bounds = [m for m in re.finditer('(?=(' + bound_pattern + '))', text)
                      if mentions_arrow(m[2], imported_arrow)
                      and (m[1].startswith(('impl ', '+'))
                           or text[:m.start()].count('(') == text[:m.start()].count(')')
                           or text[:m.start()].count('<') > text[:m.start()].count('>'))]
            if kind == 'bound' and (not bounds or (text.startswith('impl ') and '<' not in text and 'where' not in text)):
                continue
            normalized = ' '.join(text.split())
            counts[normalized] = counts.get(normalized, 0) + 1
            key = f'{path}::{kind}::{normalized}#{counts[normalized]}'
            yield key, digest(source[match.start():end])


def form_errors(source_map, registry):
    found = dict(entry for path, source in source_map.items() for entry in rust_forms(path, source))
    errors = [f'forbidden/unreviewed Rust form: {key}' for key in sorted(found.keys() - registry.keys())]
    errors.extend(f'stale Rust form: {key}' for key in sorted(registry.keys() - found.keys()))
    for key in found.keys() & registry.keys():
        rule = registry[key]
        if not rule.get('reason') or rule.get('review_sha256') != found[key]:
            errors.append(f'unreviewed Rust form: {key}')
    return errors


def runtime_registry_errors(document, found):
    errors = []
    for key, rule in document.get('python_runtime', {}).items():
        if rule.get('classification') not in {'ingresso guardato', 'non riceve dati Arrow esterni',
                                             'helper con precondizione dichiarata'} or not rule.get('reason'):
            errors.append(f'invalid runtime classification: {key}')
        references = rule.get('sources', [])
        if not references or any(ref not in found and ref not in document['support_sources'] for ref in references):
            errors.append(f'missing runtime source classification: {key}')
    for name in ('rust-macros', 'rust-reexports', 'rust-generated'):
        rule = document.get('limits', {}).get(name, {})
        if not all(rule.get(field) for field in ('rule', 'scope', 'hazard', 'reentry')):
            errors.append(f'missing inventory limit: {name}')
    return errors


def public_name(name):
    return not name.startswith('_') or (name.startswith('__') and name.endswith('__'))


def runtime_python_functions(module):
    """No signature/name heuristic: Python, native builtins and descriptors.

    Include re-exports and inherited application methods; omit object/type's
    interpreter-provided methods. Inspect attributes without invoking properties.
    """
    for name, value in vars(module).items():
        if not public_name(name):
            continue
        if inspect.isclass(value):
            members = {}
            for base in reversed(value.__mro__):
                if base.__module__ != 'builtins':
                    members.update(vars(base))
        else:
            members = {name: value}
        for member_name, function in members.items():
            if not public_name(member_name):
                continue
            if isinstance(function, (classmethod, staticmethod)):
                function = function.__func__
            if isinstance(function, property):
                function = function.fget
            if inspect.isroutine(function):
                owner = f'{name}.' if inspect.isclass(value) else ''
                yield owner + member_name


def runtime_inventory():
    package = importlib.import_module('plenora_database')
    source_package = ROOT / 'crates/plenora-database-py/python/plenora_database'
    if Path(package.__file__).resolve().is_relative_to(source_package.resolve()):
        raise ValueError('runtime inventory requires the installed wheel')
    names = {package.__name__, 'plenora_database._native'}
    names.update(info.name for info in pkgutil.walk_packages(package.__path__, package.__name__ + '.'))
    return {f'{name}::{function}' for name in sorted(names)
            for function in runtime_python_functions(importlib.import_module(name))}


def runtime_errors(registry):
    found = runtime_inventory()
    errors = [f'unclassified runtime Python function: {key}' for key in sorted(found - registry.keys())]
    # Feature/platform-specific native exports can be absent in a wheel.
    # Every callable that IS present must still have an explicit reviewed entry.
    return errors


def check():
    source_map = sources()
    found = inventory(source_map)
    document = json.loads(REGISTRY.read_text(encoding='utf-8'))
    registry = document['functions']
    errors = audit(found, registry, document['support_sources'], source_map)
    errors.extend(form_errors(source_map, document.get('rust_forms', {})))
    errors.extend(runtime_registry_errors(document, found))
    if '--python-runtime' in sys.argv:
        errors.extend(runtime_errors(document['python_runtime']))
    for path, rule in document['evidence_sources'].items():
        evidence = ROOT / path
        if not evidence.is_file() or digest(evidence.read_text(encoding='utf-8')) != rule['review_sha256']:
            errors.append(f'unreviewed or missing executable evidence: {path}')
    print(f'Static functions: {len(found)}; classifications: {len(registry)}; '
          f'runtime classifications: {len(document["python_runtime"])}')
    return errors


if __name__ == '__main__':
    errors = check()
    for error in errors:
        print(error)
    raise SystemExit(bool(errors))
